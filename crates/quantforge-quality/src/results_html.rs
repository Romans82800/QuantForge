//! SQX SaverHTML-style results export (self-contained HTML).

use quantforge_eval::{BacktestMetrics, ScoutResult, Trade};
use serde_json::Value;
use std::fmt::Write as _;

pub const HTML_REPORT_PROTOCOL: &str = "results-html-v1";

/// Render a compact Dark-friendly HTML report from Scout/Judge metrics + trades.
pub fn render_results_html(
    title: &str,
    strategy_id: &str,
    metrics: &BacktestMetrics,
    trades: &[Trade],
    extras: &[(String, String)],
) -> String {
    let mut rows = String::new();
    for (index, trade) in trades.iter().enumerate() {
        let _ = writeln!(
            rows,
            "<tr><td>{}</td><td>{}</td><td>{:.5}</td><td>{:.5}</td><td>{:.2}</td><td>{:.2}</td><td>{:?}</td></tr>",
            index + 1,
            match trade.side {
                quantforge_eval::PositionSide::Long => "Long",
                quantforge_eval::PositionSide::Short => "Short",
            },
            trade.entry_price,
            trade.exit_price,
            trade.volume,
            trade.net_profit,
            trade.exit_reason,
        );
    }
    let mut extra_html = String::new();
    for (key, value) in extras {
        let _ = writeln!(
            extra_html,
            "<div class=\"kpi\"><span>{}</span><strong>{}</strong></div>",
            escape(key),
            escape(value)
        );
    }
    format!(
        r#"<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8"/>
<title>{title}</title>
<style>
body{{margin:0;font:14px/1.45 "Segoe UI",sans-serif;background:#1b1d21;color:#e6e8ec}}
main{{max-width:1100px;margin:0 auto;padding:24px}}
h1{{font-size:22px;margin:0 0 4px}}
.sub{{color:#9aa3af;margin-bottom:20px}}
.grid{{display:grid;grid-template-columns:repeat(auto-fit,minmax(140px,1fr));gap:10px;margin-bottom:22px}}
.kpi{{background:#252830;border:1px solid #333845;padding:12px 14px}}
.kpi span{{display:block;color:#9aa3af;font-size:11px;text-transform:uppercase;letter-spacing:.04em}}
.kpi strong{{font-size:18px}}
table{{width:100%;border-collapse:collapse;background:#252830}}
th,td{{padding:8px 10px;border-bottom:1px solid #333845;text-align:left}}
th{{color:#9aa3af;font-size:11px;text-transform:uppercase}}
footer{{margin-top:18px;color:#6b7380;font-size:12px}}
</style>
</head>
<body>
<main>
<h1>{title}</h1>
<p class="sub">{strategy} · {protocol}</p>
<div class="grid">
<div class="kpi"><span>Trades</span><strong>{trades}</strong></div>
<div class="kpi"><span>Return %</span><strong>{ret:.2}</strong></div>
<div class="kpi"><span>Profit factor</span><strong>{pf}</strong></div>
<div class="kpi"><span>Max DD %</span><strong>{dd:.2}</strong></div>
<div class="kpi"><span>Net profit</span><strong>{net:.2}</strong></div>
{extras}
</div>
<table>
<thead><tr><th>#</th><th>Side</th><th>Entry</th><th>Exit</th><th>Vol</th><th>Net</th><th>Reason</th></tr></thead>
<tbody>
{rows}
</tbody>
</table>
<footer>Generated by QuantForge ({protocol}). Behavioral stand-in for SQX SaverHTML.</footer>
</main>
</body>
</html>
"#,
        title = escape(title),
        strategy = escape(strategy_id),
        protocol = HTML_REPORT_PROTOCOL,
        trades = metrics.trade_count,
        ret = metrics.return_percent,
        pf = metrics
            .profit_factor
            .map(|v| format!("{v:.2}"))
            .unwrap_or_else(|| "∞".into()),
        dd = metrics.max_drawdown_percent,
        net = metrics.net_profit,
        extras = extra_html,
        rows = if rows.is_empty() {
            "<tr><td colspan=\"7\">No trades</td></tr>".into()
        } else {
            rows
        },
    )
}

pub fn render_results_html_from_scout(
    title: &str,
    strategy_id: &str,
    result: &ScoutResult,
    extras: &[(String, String)],
) -> String {
    render_results_html(title, strategy_id, &result.metrics, &result.trades, extras)
}

/// Best-effort extract metrics/trades from a Scout/Judge/Challenge-like JSON value.
pub fn render_results_html_from_json(title: &str, value: &Value) -> Result<String, String> {
    let strategy_id = value
        .pointer("/strategy/id")
        .or_else(|| value.get("strategy_id"))
        .or_else(|| value.pointer("/binding/strategy_id"))
        .and_then(|v| v.as_str())
        .unwrap_or("strategy");
    let result = value
        .get("result")
        .cloned()
        .or_else(|| value.get("scout").cloned())
        .unwrap_or_else(|| value.clone());
    let metrics: BacktestMetrics = serde_json::from_value(
        result
            .get("metrics")
            .cloned()
            .or_else(|| value.get("metrics").cloned())
            .ok_or_else(|| "JSON missing metrics".to_string())?,
    )
    .map_err(|error| error.to_string())?;
    let trades: Vec<Trade> = serde_json::from_value(
        result
            .get("trades")
            .cloned()
            .or_else(|| value.get("trades").cloned())
            .unwrap_or(Value::Array(vec![])),
    )
    .map_err(|error| error.to_string())?;
    Ok(render_results_html(title, strategy_id, &metrics, &trades, &[]))
}

fn escape(value: &str) -> String {
    value
        .replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
}

#[cfg(test)]
mod tests {
    use super::*;
    use quantforge_eval::{ExitReason, PositionSide};

    #[test]
    fn html_contains_metrics_and_trade_row() {
        let metrics = BacktestMetrics {
            initial_balance: 10_000.0,
            ending_balance: 10_125.0,
            net_profit: 125.0,
            return_percent: 12.5,
            trade_count: 1,
            winning_trades: 1,
            losing_trades: 0,
            win_rate: 1.0,
            profit_factor: Some(1.8),
            max_drawdown: 40.0,
            max_drawdown_percent: 4.0,
            sharpe_ratio: None,
            expectancy: 125.0,
        };
        let trades = vec![Trade {
            side: PositionSide::Long,
            entry_timestamp_ms: 1,
            exit_timestamp_ms: 2,
            entry_price: 1.1,
            exit_price: 1.2,
            volume: 1.0,
            initial_stop_loss: 1.0,
            initial_take_profit: 1.3,
            gross_profit: 10.0,
            commission: 0.0,
            swap: 0.0,
            net_profit: 10.0,
            bars_held: 1,
            exit_reason: ExitReason::TakeProfit,
        }];
        let html = render_results_html("Demo", "demo-id", &metrics, &trades, &[]);
        assert!(html.contains("12.50"));
        assert!(html.contains("TakeProfit"));
        assert!(html.contains(HTML_REPORT_PROTOCOL));
    }
}
